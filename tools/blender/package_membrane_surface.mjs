import assert from 'node:assert/strict';
import { createHash } from 'node:crypto';
import { readFileSync, writeFileSync } from 'node:fs';
import { encodeGlb, readGlb, validateRuntimeRig } from './runtime_rig_contract.mjs';
const [source, configuration, output] = process.argv.slice(2);
const bytes = readFileSync(source);
validateRuntimeRig(bytes);
const config = JSON.parse(readFileSync(configuration));
const { gltf, binary } = readGlb(bytes);
const node = gltf.nodes.find(n => n.name === 'WyvernMembrane_ExportSafe');
assert.ok(node && !node.extras?.membraneSurfaceRepair);
assert.equal(config.sourceVertexCount, gltf.accessors[gltf.meshes[node.mesh].primitives[0].attributes.POSITION].count);
node.extras = { ...node.extras, membraneSurfaceRepair: config };
const candidate = encodeGlb(gltf, binary);
const decoded = readGlb(candidate), baseline = readGlb(bytes);
assert.ok(decoded.binary.equals(baseline.binary));
const target = decoded.gltf.nodes.find(n => n.name === node.name);
delete target.extras.membraneSurfaceRepair;
if (!Object.keys(target.extras).length) delete target.extras;
assert.deepEqual(decoded.gltf, baseline.gltf);
writeFileSync(output, candidate, { flag: 'wx' });
console.log(JSON.stringify({ bytes: candidate.length, source_sha256: createHash('sha256').update(bytes).digest('hex'), candidate_sha256: createHash('sha256').update(candidate).digest('hex'), policy: 'Original GLB data preserved; Flight Lab applies the exported surface solver' }, null, 2));
